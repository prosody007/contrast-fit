import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
// Only this fixed generated directory is ever removed; no CLI path is accepted.
const output = new URL("dist/", root);
const compilerOutput = new URL(".compiler/", output);
const source = new URL("src/contrast-fit.js", root);
const declarations = new URL("src/contrast-fit.d.ts", root);
const banner = "// Generated by npm run build:lib. Edit src/contrast-fit.js instead.\n";

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
try {
  // TypeScript's maintained module emitter handles syntax. Do not rewrite exports
  // with regular expressions, or rely on its deliberately unstable compiler API.
  execFileSync(process.execPath, [
    fileURLToPath(new URL("node_modules/typescript/bin/tsc", root)),
    "--ignoreConfig", "--allowJs", "--noCheck", "--module", "commonjs",
    "--target", "es2022", "--outDir", fileURLToPath(compilerOutput),
    fileURLToPath(source),
  ], { cwd: fileURLToPath(root), stdio: "inherit" });
  const compiledFiles = await readdir(compilerOutput);
  assert.deepEqual(compiledFiles, ["contrast-fit.js"], "build expects one standalone, dependency-free source module");
  const commonjs = await readFile(new URL("contrast-fit.js", compilerOutput), "utf8");
  // A browser wrapper around compiler-emitted CommonJS is safe only while there
  // are no imports/re-exports. This guards accidental new runtime dependencies.
  assert.doesNotMatch(commonjs, /\brequire\s*\(/, "runtime imports need an explicit bundler decision");
  const esm = await readFile(source, "utf8");
  const types = await readFile(declarations, "utf8");
  await Promise.all([
    writeFile(new URL("contrast-fit.js", output), banner + esm),
    writeFile(new URL("contrast-fit.cjs", output), banner + commonjs),
    writeFile(new URL("contrast-fit.d.ts", output), types),
    writeFile(new URL("contrast-fit.d.cts", output), types),
    writeFile(new URL("contrast-fit.global.js", output), banner +
      "(() => {\n  const exports = {};\n" + commonjs +
      "\n  globalThis.ContrastFit = Object.freeze(exports);\n})();\n"),
  ]);
  console.log("Library build: ESM, CommonJS, browser global and dual TypeScript declarations passed");
} finally {
  await rm(compilerOutput, { recursive: true, force: true });
}
